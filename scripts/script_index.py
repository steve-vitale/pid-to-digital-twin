"""Generate docs/SCRIPTS.md: every script, what kind it is (a tool for your data, a check, support, or research
record), and what it does in its own words.

    python scripts/script_index.py            # write docs/SCRIPTS.md
    python scripts/script_index.py --check    # exit 1 if a script is unregistered, a registered one is gone, a tool
                                              # has no guide, a guide file is missing, or docs/SCRIPTS.md is stale

The kinds live in data/script_index.json; each description is the first sentence of the script's own docstring (or
the registry's "purpose" for a non-Python file), so the index can't drift from the code. Test scripts (test_*.py)
are not listed. Stdlib only.
"""
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "data" / "script_index.json"
OUT = ROOT / "docs" / "SCRIPTS.md"
ORDER = ["tool", "check", "support", "research"]


def discover():
    found = set()
    for pattern in ("*.py", "*.ps1", "ignition/*.py", "ignition/acceptance/*.py", "ignition/acceptance/*.js"):
        for p in (ROOT / "scripts").glob(pattern):
            if not p.name.startswith("test_") and p.name != "__init__.py":
                found.add(p.relative_to(ROOT).as_posix())
    return found


def first_sentence(path, override=None):
    if override:
        return override
    text = (ROOT / path).read_text(encoding="utf-8-sig")
    try:
        doc = ast.get_docstring(ast.parse(text)) or ""
    except SyntaxError:
        doc = ""
    doc = " ".join(doc.split())
    if not doc:
        return ""
    m = re.match(r"(.+?[.!?])(\s|$)", doc)  # a colon introduces the rest of the sentence; it doesn't end it
    return (m.group(1) if m else doc)[:220]


def problems(reg, found):
    out = []
    listed = set(reg["scripts"])
    out += [f"{p}: not in data/script_index.json (give it a kind)" for p in sorted(found - listed)]
    out += [f"{p}: listed in data/script_index.json but the file is gone" for p in sorted(listed - found)]
    for p, e in sorted(reg["scripts"].items()):
        if e.get("kind") not in reg["kinds"]:
            out.append(f"{p}: unknown kind {e.get('kind')!r}")
        if e.get("kind") == "tool" and not e.get("guide"):
            out.append(f"{p}: a tool needs a guide showing its use")
        if e.get("guide") and not (ROOT / e["guide"]).exists():
            out.append(f"{p}: guide {e['guide']} does not exist")
        if p in found and not first_sentence(p, e.get("purpose")):
            out.append(f"{p}: no docstring (or registry purpose) to say what it does")
    return out


def render(reg):
    lines = ["# Scripts: what each one is for", "",
             "Generated by `scripts/script_index.py` from `data/script_index.json` and each script's own docstring. "
             "Only the **tools** are meant for your own drawings, models or data; the research record reproduces "
             "this project's results and is not built for other inputs. Tests (`test_*.py`) are not listed.", ""]
    for kind in ORDER:
        rows = sorted((p, e) for p, e in reg["scripts"].items() if e["kind"] == kind)
        lines += [f"## {reg['kinds'][kind]} ({len(rows)})", "", "| Script | What it does | Shown in |", "|---|---|---|"]
        for p, e in rows:
            what = first_sentence(p, e.get("purpose")).replace("|", "\\|")
            guide = f"[{Path(e['guide']).name}](../{e['guide']})" if e.get("guide") else ""
            lines.append(f"| [`{p.removeprefix('scripts/')}`](../{p}) | {what} | {guide} |")
        lines.append("")
    return "\n".join(lines)


USAGE = "usage: python scripts/script_index.py [--check]"


def main(argv):
    if "-h" in argv or "--help" in argv:  # print usage; never regenerate anything on a help request
        print(__doc__)
        return 0
    unknown = [a for a in argv if a != "--check"]
    if unknown:  # a typo such as --chek must not silently regenerate docs/SCRIPTS.md
        print(f"{USAGE}\nscript_index.py: error: unrecognized argument(s): {' '.join(unknown)}", file=sys.stderr)
        return 2
    reg = json.loads(REGISTRY.read_text(encoding="utf-8"))
    bad = problems(reg, discover())
    text = render(reg) if not bad else None
    if "--check" in argv:
        if not bad and (not OUT.exists() or OUT.read_text(encoding="utf-8") != text):
            bad.append("docs/SCRIPTS.md is stale: run python scripts/script_index.py")
        for b in bad:
            print("FAIL:", b)
        print(f"{len(reg['scripts'])} scripts indexed; {len(bad)} problem(s)")
        return 1 if bad else 0
    if bad:
        for b in bad:
            print("FAIL:", b)
        return 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    counts = {k: sum(e["kind"] == k for e in reg["scripts"].values()) for k in ORDER}
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}: {counts}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
