"""The deliverables matrix: what the TE track (process knowledge, no drawing) and the OPEN100 track (drawings, no
process data) can each deliver. docs/deliverables_matrix.json is the source; docs/DELIVERABLES.md is generated from it
(the README keeps a short summary that links there).

  python scripts/deliverables_matrix.py            # print the table
  python scripts/deliverables_matrix.py --write    # write docs/DELIVERABLES.md
  python scripts/deliverables_matrix.py --check    # exit 1 if the matrix breaks its rules or docs/DELIVERABLES.md is stale
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MATRIX = ROOT / "docs" / "deliverables_matrix.json"
TARGET = ROOT / "docs" / "DELIVERABLES.md"
PREFIX = "../"  # evidence paths are repository-relative; DELIVERABLES.md sits in docs/
START, END = "<!-- deliverables-matrix:start -->", "<!-- deliverables-matrix:end -->"
HEADING = "What you can do with only drawings, only process knowledge, or both"
WORDS = {"done": "Done", "done_offline": "Done offline (not in a gateway)", "partial": "Partial", "draft": "Draft",
         "mockup": "Mockup", "synthetic_demo": "Synthetic demo", "not_done": "Not done yet",
         "not_possible": "Not possible", "not_applicable": "Not applicable"}

INTRO = """\
*Generated by `scripts/deliverables_matrix.py` from [deliverables_matrix.json](deliverables_matrix.json); edit the
JSON, then run `python scripts/deliverables_matrix.py --write`. A short summary is in the
[README](../README.md#drawings-only-process-knowledge-only-or-both).*

The two main tracks have opposite halves of the picture. **TE** has process knowledge (a model checked against the
simulator source, and recorded simulator replay) and no original drawing. **OPEN100** has 12 real drawings and
no process data. Most of a digital twin starter kit needs only the structure, and drawings carry structure: equipment,
connections, flow arrows, off-page links, isolation valves. Values, normal bands, alarms and replay need process data,
so OPEN100 can't have them, and the table says so instead of faking them. What OPEN100 gets from its drawings alone is
in [OPEN100_STRUCTURAL.md](OPEN100_STRUCTURAL.md): flow direction read from arrowheads, flags and pump ports
(361 of 1,133 process links; the rest stay undirected), the 12 sheets stitched into one plant, an ISA-101-style mimic,
a 3D orientation tour and a LOTO isolation view on the real drawing (a mockup, not a procedure: a valve the
extraction missed is not on the list).
"""

SCREENS = """\
| OPEN100 plant overview (offline render) | 3D tour stop, structure only | LOTO isolation view on the real drawing (mockup) |
|---|---|---|
| ![OPEN100 plant overview: 12 areas in inferred tour order, arrows between areas where off-page flags show the direction, every value 'not connected'](screenshots/open100/mimic-plant-overview.png) | ![3D tour stop 5, aux cooling water: placeholder equipment at drawing positions, purpose card from the drawing's equipment schedule, instruments marked not connected](screenshots/open100/3d-05_stop_sheet7.jpg) | ![OPEN100 sheet 7 with numbered isolation points: manual and motor-operated valves, motor-driven pumps, lines from other systems, control valves marked as not isolation devices](screenshots/open100/loto-isolation-sheet7.png) |
"""


def load():
    return json.loads(MATRIX.read_text(encoding="utf-8"))


def problems(doc, root=ROOT):
    """Matrix rules: known statuses, a reason wherever something is not fully done, evidence that exists."""
    out = []
    for r in doc["rows"]:
        for t in ("te", "open100"):
            c = r[t]
            if c["status"] not in doc["statuses"] or c["status"] not in WORDS:
                out.append("%s / %s: unknown status %r" % (r["deliverable"], t, c["status"]))
            if c["status"] != "done" and not c.get("note", "").strip():
                out.append("%s / %s: %s needs a reason" % (r["deliverable"], t, c["status"]))
            if c["status"] in ("not_possible", "not_applicable") and c.get("evidence"):
                out.append("%s / %s: %s cannot cite evidence of being done" % (r["deliverable"], t, c["status"]))
            if c["status"] not in ("not_possible", "not_applicable") and not c.get("evidence"):
                out.append("%s / %s: %s needs evidence" % (r["deliverable"], t, c["status"]))
            for e in c.get("evidence", []):
                if not (root / e).exists():
                    out.append("%s / %s: evidence missing: %s" % (r["deliverable"], t, e))
    return out


def cell(c, prefix=PREFIX):
    text = "**%s**" % WORDS[c["status"]]
    if c.get("note"):
        text += ": " + c["note"]
    links = ["[%s](%s%s)" % (Path(e).name, prefix, e) for e in c.get("evidence", [])[:2]]
    if links:
        text += " (" + ", ".join(links) + ")"
    return text.replace("|", "\\|")


def markdown(doc, prefix=PREFIX):
    """The table. prefix goes before every repository-relative evidence path ("../" for docs/DELIVERABLES.md)."""
    lines = ["| Deliverable | TE: process knowledge, no original drawing | OPEN100: drawings, no process data |",
             "|---|---|---|"]
    for r in doc["rows"]:
        lines.append("| %s | %s | %s |" % (r["deliverable"], cell(r["te"], prefix), cell(r["open100"], prefix)))
    return "\n".join(lines)


def page(doc):
    """The whole of docs/DELIVERABLES.md."""
    return "\n".join(["# " + HEADING, "", INTRO, START, markdown(doc), END, "", SCREENS])


def write_page(doc):
    TARGET.write_text(page(doc), encoding="utf-8", newline="\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true", help="write docs/DELIVERABLES.md")
    g.add_argument("--check", action="store_true", help="exit 1 if a rule is broken or docs/DELIVERABLES.md is stale")
    a = ap.parse_args(argv)
    doc = load()
    bad = problems(doc)
    if a.check:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else None
        if current != page(doc):
            bad.append("docs/DELIVERABLES.md is stale or missing: run python scripts/deliverables_matrix.py --write")
        print("\n".join(bad) if bad else "deliverables matrix: rules hold and docs/DELIVERABLES.md is current")
        return 1 if bad else 0
    if bad:
        raise SystemExit("\n".join(bad))
    if a.write:
        write_page(doc)
        print("docs/DELIVERABLES.md written")
    else:
        print(markdown(doc, prefix=""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
