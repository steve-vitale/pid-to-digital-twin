"""Re-score the committed scorecards and replicate tables from committed predictions alone. Offline; no model calls.

The run records under runs/ hold raw model output and stay out of git (runs/README.md). What the scorers read from a
record is small: the parsed prediction and a few metadata fields. That is committed under

    predictions/<label>/<tool>/<drawing>.json

one file per drawing per tool, holding only:
  - the parsed prediction: every symbol with only the fields a scorer reads (id, class, box or bbox, tag,
    confidence), and every connection unchanged (the scorer keys an unmatched connection by its full text);
  - the record metadata the scorers and tables print: tool, drawing, label, model, prompt file and hash, image
    hash, run date, seconds, cost (metered and notional), error and parse error strings, the source label of a
    traced run, and the few tiling and tracer fields score_te_roundtrip.py reports.
No raw model text, tile transcripts, token usage or tracer statistics are kept.

--check rebuilds a temporary runs/ tree from predictions/ (never touching the real runs/ or out/), runs the
unchanged scorers on it (scorecard.py, replicate_stats.py, score_te_roundtrip.py) against the committed answer keys,
and compares every regenerated file with the committed one in out/. Files are compared after CRLF -> LF, i.e. against
the bytes git stores, so a Windows and a Linux checkout agree.

Each committed table ends up in one of four states:
  MATCH   regenerated byte for byte;
  DIFF    regenerated and different (exit status 1);
  GAP     its predictions are not committed, for a reason listed in KNOWN_GAPS below (reported, not a failure);
  SKIP    the answer keys are not in this checkout (holdout B is downloaded, not committed: scripts/fetch_pid2graph.py).
A table whose predictions are missing and that is NOT in KNOWN_GAPS is a failure too, so a gap can't open silently.

Usage:
  python scripts/rescore.py --check [--label X]   # regenerate and diff; exit 1 on any difference
  python scripts/rescore.py --list                # each table, its labels and whether predictions are committed
  python scripts/rescore.py --export [--label X]  # author only: write predictions/ from the local runs/
"""
import argparse
import contextlib
import io
import json
import shutil
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

ROOT = Path(__file__).resolve().parent.parent
PREDICTIONS = ROOT / "predictions"
PID2GRAPH = ROOT / "data" / "external" / "pid2graph" / "PID2Graph" / "Complete"
SCHEMA = "pid-prediction/1"

META_KEYS = ("tool", "drawing", "label", "model", "prompt_file", "prompt_sha256", "image_sha256", "ran_at",
             "seconds", "cost_usd", "cost_usd_notional", "error", "parse_error", "source_label")
TILING_KEYS = ("grid", "overlap", "preface_sha256", "tile_seconds_sum", "tiles_failed")
TRACER_KEYS = ("script", "mode", "seconds", "ran_at")
SYMBOL_KEYS = ("id", "class", "box", "bbox", "tag", "confidence")

# Committed tables whose original predictions have not been located. Each entry says why.
# Preserved research checkouts supplied the round-5 and revision-A TE records (predictions/RECOVERY.json).
# rescore.py --check reports the remaining cases as GAP; anything else missing is a failure.
ABSENT = ("its run records were not under runs/ on the machine the predictions were exported from (2026-10-29), "
          "and the repository records no copy or reason")
KNOWN_GAPS = {
    "out/scorecard_r2-tiles-2x2-ov_dev": f"re-merge variant (scripts/remerge_tiles.py, attempt A043): {ABSENT}",
    "out/scorecard_r2-tiles-2x2-repeat-ov_dev": f"re-merge variant (attempt A043): {ABSENT}",
    "out/scorecard_r2-trace-oracle_dev": f"oracle tracer (answer-key symbols, no model; scripts/trace_connections.py "
                                         f"--oracle can rebuild it): {ABSENT}",
    "out/scorecard_r2-trace-union_dev": f"union variant (attempt A026): {ABSENT}",
    "out/scorecard_r2-trace_dev": "runs/r2-trace on the export machine holds drawings 6-11 only, for every tool; the "
                                  "development drawings 0-5 this scorecard scored are not there",
}
# Written by scorecard.py before commit 3caf420, which added the review-load column and the "(split: ...)" title.
# The current scorer regenerates every other byte; --check verifies exactly that and reports MATCH-OLD.
PRE_REVIEW_LOAD = {"out/scorecard_first-try", "out/scorecard_repeat-v1", "out/scorecard_smoke",
                   "out/scorecard_v2-named-fields", "out/scorecard_v2-open-weight-gemma",
                   "out/scorecard_v2-open-weight-gemma-retry"}
# Revision A predates the source-location line added when revision C was archived. All table and JSON bytes
# still compare, with only this exact added line removed from the regenerated markdown.
PRE_KEY_HEADER = {"out/te_pid/roundtrip_scores"}


# ---------------------------------------------------------------- the committed prediction format

def slim(record):
    """A run record -> the committed prediction file's content (no raw model text)."""
    out = {"schema": SCHEMA}
    for k in META_KEYS:
        if k in record:
            out[k] = record[k]
    if isinstance(record.get("tiling"), dict):
        out["tiling"] = {k: record["tiling"][k] for k in TILING_KEYS if k in record["tiling"]}
    if isinstance(record.get("tracer"), dict):
        out["tracer"] = {k: record["tracer"][k] for k in TRACER_KEYS if k in record["tracer"]}
    pred = record.get("prediction")
    if isinstance(pred, dict):
        slim_pred = {}
        if "symbols" in pred:
            syms = pred["symbols"]
            slim_pred["symbols"] = [{k: s[k] for k in SYMBOL_KEYS if k in s} if isinstance(s, dict) else s
                                    for s in syms] if isinstance(syms, list) else syms
        if "connections" in pred:
            slim_pred["connections"] = pred["connections"]
        pred = slim_pred
    out["prediction"] = pred
    return out


def dumps(obj):
    """Stable text: metadata one key per line, one symbol or connection per line, UTF-8, LF."""
    j = lambda v: json.dumps(v, ensure_ascii=False, separators=(",", ":"))  # noqa: E731
    lines = ["{"]
    items = [(k, v) for k, v in obj.items() if k != "prediction"]
    for k, v in items:
        lines.append(f" {j(k)}: {j(v)},")
    pred = obj.get("prediction")
    if isinstance(pred, dict) and all(isinstance(pred.get(k), list) for k in pred):
        lines.append(' "prediction": {')
        parts = list(pred.items())
        for i, (k, seq) in enumerate(parts):
            end = "," if i < len(parts) - 1 else ""
            if not seq:
                lines.append(f"  {j(k)}: []{end}")
                continue
            lines.append(f"  {j(k)}: [")
            lines += [f"   {j(x)}," for x in seq[:-1]] + [f"   {j(seq[-1])}"]
            lines.append(f"  ]{end}")
        lines.append(" }")
    else:
        lines.append(f' "prediction": {j(pred)}')
    lines.append("}")
    text = "\n".join(lines) + "\n"
    assert json.loads(text) == obj, "prediction file does not round-trip"
    return text


def record_from(prediction_file):
    """A committed prediction file -> a run record the unchanged scorers can read."""
    rec = json.loads(Path(prediction_file).read_text(encoding="utf-8"))
    rec.pop("schema", None)
    return rec


def export(labels):
    runs = ROOT / "runs"
    written = 0
    for label in labels:
        src = runs / label
        dest = PREDICTIONS / label
        if dest.exists():
            shutil.rmtree(dest)
        for f in sorted(src.glob("*/*.json")):
            out = dest / f.parent.name / f.name
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(dumps(slim(json.loads(f.read_text(encoding="utf-8")))).encode("utf-8"))
            written += 1
    return written


# ---------------------------------------------------------------- which committed table comes from which runs

def scorecard_job(path):
    """out/scorecard_<label>[_<split>].md -> how scorecard.py produced it.

    The answer-key set is not printed in the scorecard, so it follows the scripts that made them:
    holdout B (hb-*) is PID2Graph's "Dataset PID" (scripts/score_holdout_b.ps1); round-4 scan labels are scored
    against their own degraded copies (scripts/score_scan_robustness.ps1), except the L3 symbols traced on the clean
    image; everything else is OPEN100."""
    stem = path.stem[len("scorecard_"):]
    label, split = stem, "all"
    for s in ("dev", "holdout-a"):
        if stem.endswith("_" + s):
            label, split = stem[: -len(s) - 1], s
    dataset = "PID2Graph OPEN100"
    if label.startswith("hb-"):
        dataset = "Dataset PID"
    elif label.startswith("r4-scan-L") and label.endswith(("-tiles", "-trace")) and "symbols-clean" not in label:
        dataset = f"PID2Graph OPEN100 scan-L{label[len('r4-scan-L')]}"
    return {"kind": "scorecard", "name": f"out/{path.stem}", "files": [path, path.with_suffix(".json")],
            "labels": [label], "split": split, "dataset": dataset, "keys_dir": PID2GRAPH / dataset}


def replicate_job(path):
    meta = json.loads(path.read_text(encoding="utf-8"))
    md = path.with_suffix(".md")
    import replicate_stats as rs
    # A hand-annotated markdown (the diagnostic's extra header) is not generator output: compare the JSON only.
    generated_md = md.exists() and md.read_text(encoding="utf-8").startswith(f"# Replicates: {meta['set']}\n")
    files = [path] + ([md] if generated_md else [])
    return {"kind": "replicates", "name": f"out/{path.stem}", "files": files, "labels": meta["labels"],
            "set": meta["set"], "tools": meta["tools"], "keys_dir": rs.SETS[meta["set"]]["dir"],
            "note": None if generated_md else "markdown carries a hand-written header; JSON compared only"}


def roundtrip_job(path):
    md = path.with_suffix(".md").read_text(encoding="utf-8")
    meta = json.loads(path.read_text(encoding="utf-8"))
    conds = list(dict.fromkeys(r["condition"] for r in meta["summary"]))
    tools = list(dict.fromkeys(r["tool"] for r in meta["summary"]))
    labels = sorted({r["label"] for r in meta["runs"]})
    line = next((x for x in md.splitlines() if x.startswith("Sheets and keys:")), None)
    if line:
        keys, prefix = line.split("`")[1], line.split("`")[3][:-2]
    else:
        # Written before the scorer printed its keys (revision A, journal entry 44): the scorer's documented
        # revision-A settings. The current scorer would add that header line, so this file can't match as it is.
        keys, prefix = "data/te_pid/rev-a", labels[0].split("-")[0]
    return {"kind": "roundtrip", "name": f"out/te_pid/{path.stem}", "files": [path.with_suffix(".md"), path],
            "labels": labels, "prefix": prefix, "keys": keys, "conditions": conds, "tools": tools,
            "keys_dir": ROOT / keys}


def jobs():
    out = [scorecard_job(p) for p in sorted((ROOT / "out").glob("scorecard_*.md"))]
    out += [replicate_job(p) for p in sorted((ROOT / "out").glob("replicates_*.json"))]
    out += [roundtrip_job(p) for p in sorted((ROOT / "out" / "te_pid").glob("roundtrip_scores*.json"))]
    return out


# ---------------------------------------------------------------- regenerate into a temporary tree

def materialize(tmp, label):
    """predictions/<label> -> tmp/runs/<label> as run records; also the source labels a traced run names."""
    src = PREDICTIONS / label
    if not src.is_dir():
        return False
    dest = tmp / "runs" / label
    if dest.exists():
        return True
    for f in sorted(src.glob("*/*.json")):
        out = dest / f.parent.name / f.name
        out.parent.mkdir(parents=True, exist_ok=True)
        rec = record_from(f)
        out.write_text(json.dumps(rec), encoding="utf-8")
        if rec.get("source_label"):
            materialize(tmp, rec["source_label"])
    return True


def regenerate(job, tmp):
    """Run the unchanged scorer with its runs/ and out/ pointed at tmp. Returns {committed path: regenerated path}."""
    sink = io.StringIO()
    if job["kind"] == "scorecard":
        import scorecard
        scorecard.ROOT, scorecard.DATA = tmp, job["keys_dir"]
        argv = ["scorecard.py", "--label", job["labels"][0], "--split", job["split"]]
        with contextlib.redirect_stdout(sink), _argv(argv):
            scorecard.main()
        return {f: tmp / "out" / f.name for f in job["files"]}
    if job["kind"] == "replicates":
        import replicate_stats
        replicate_stats.ROOT = tmp
        stem = job["files"][0].stem
        argv = ["replicate_stats.py", "--set", job["set"], "--labels", ",".join(job["labels"]),
                "--tools", ",".join(job["tools"]), "--out", str(tmp / "out" / stem)]
        with contextlib.redirect_stdout(sink), _argv(argv):
            replicate_stats.main()
        return {f: tmp / "out" / f.name for f in job["files"]}
    if job["kind"] == "roundtrip":
        import score_te_roundtrip as te
        te.ROOT = tmp
        keys = tmp / job["keys"]  # the scorer joins ROOT and --keys, and prints --keys: copy the keys in place
        keys.mkdir(parents=True, exist_ok=True)
        for f in job["keys_dir"].iterdir():
            if f.is_file():
                shutil.copy2(f, keys / f.name)
        stem = job["files"][1].stem
        argv = ["score_te_roundtrip.py", "--keys", job["keys"], "--prefix", job["prefix"], "--out", stem,
                "--conditions", ",".join(job["conditions"]), "--tools", ",".join(job["tools"])]
        with contextlib.redirect_stdout(sink), _argv(argv):
            te.main()
        return {f: tmp / "out" / "te_pid" / f.name for f in job["files"]}
    raise ValueError(job["kind"])


@contextlib.contextmanager
def _argv(argv):
    old = sys.argv
    sys.argv = argv
    try:
        yield
    finally:
        sys.argv = old


def lf(path):
    return path.read_bytes().replace(b"\r\n", b"\n")


def first_difference(a, b):
    la, lb = a.decode("utf-8", "replace").split("\n"), b.decode("utf-8", "replace").split("\n")
    for i, (x, y) in enumerate(zip(la, lb), 1):
        if x != y:
            return f"line {i}: committed {x[:160]!r} / regenerated {y[:160]!r}"
    return f"line count: committed {len(la)} / regenerated {len(lb)}"


SPLITS = {"all": None, "dev": {str(i) for i in range(6)}, "holdout-a": {str(i) for i in range(6, 12)}}


def short_drawings(job):
    """Scorecards: tools whose committed drawing count is more than the predictions committed for that split."""
    if job["kind"] != "scorecard" or not job["files"][1].exists():
        return []
    committed = json.loads(job["files"][1].read_text(encoding="utf-8"))
    wanted, base, out = SPLITS[job["split"]], PREDICTIONS / job["labels"][0], []
    for tool, s in committed.items():
        have = [p.stem for p in (base / tool).glob("*.json") if wanted is None or p.stem in wanted]
        if len(have) < s.get("drawings", 0):
            out.append(f"{tool}: scorecard scored {s['drawings']} drawings, predictions hold {len(have)}")
    return out


def without_review_load(name, data):
    """The current scorecard output with what commit 3caf420 added taken out again (the column, the JSON field and
    the split in the title), for the PRE_REVIEW_LOAD tables."""
    if name.endswith(".json"):
        summary = json.loads(data)
        for s in summary.values():
            s.pop("review_load_per_100", None)
        return json.dumps(summary, indent=1).encode("utf-8")
    lines = data.decode("utf-8").split("\n")
    lines[0] = lines[0].replace(" (split: all)", "")
    for i, line in enumerate(lines):
        if line.startswith("| Tool | Model |"):
            j = i
            while j < len(lines) and lines[j].startswith("|"):
                cells = lines[j].split("|")
                del cells[4]
                lines[j] = "|".join(cells)
                j += 1
            break
    return "\n".join(lines).encode("utf-8")


def check_job(job):
    """-> (state, detail lines)."""
    missing = [lb for lb in job["labels"] if not (PREDICTIONS / lb).is_dir()]
    short = [] if missing else short_drawings(job)
    if short:
        reason = KNOWN_GAPS.get(job["name"])
        if reason:
            return "GAP", [f"{reason} ({'; '.join(short)})"]
        return "MISSING", short + ["no reason is recorded in KNOWN_GAPS"]
    if missing:
        reason = KNOWN_GAPS.get(job["name"])
        if reason:
            return "GAP", [f"predictions not committed for {', '.join(missing)}: {reason}"]
        return "MISSING", [f"predictions not committed for {', '.join(missing)} and no reason is recorded in "
                           "KNOWN_GAPS"]
    if not job["keys_dir"].is_dir():
        return "SKIP", [f"answer keys not in this checkout: {job['keys_dir'].relative_to(ROOT)} "
                        "(holdout B: python scripts/fetch_pid2graph.py)"]
    with tempfile.TemporaryDirectory(prefix="rescore-") as d:
        tmp = Path(d)
        (tmp / "out" / "te_pid").mkdir(parents=True)
        for lb in job["labels"]:
            materialize(tmp, lb)
        made = regenerate(job, tmp)
        details, old = [], job["name"] in PRE_REVIEW_LOAD
        old_keys = job["name"] in PRE_KEY_HEADER
        for committed, regenerated in made.items():
            rel = committed.relative_to(ROOT).as_posix()
            if not regenerated.exists():
                details.append(f"{rel}: not regenerated")
                continue
            new = lf(regenerated)
            if old:
                new = without_review_load(rel, new)
            if old_keys and committed.suffix == ".md":
                header = f"Sheets and keys: `{job['keys']}`; runs `{job['prefix']}-*`.\n\n".encode("utf-8")
                new = new.replace(header, b"", 1)
            if lf(committed) != new:
                details.append(f"{rel}: differs at {first_difference(lf(committed), new)}")
    if job.get("note"):
        details.append(job["note"])
    if any(": differs" in x or "not regenerated" in x for x in details):
        return "DIFF", details
    details.insert(0, ", ".join(f.relative_to(ROOT).as_posix() for f in job["files"]))
    if old:
        details.append("written before commit 3caf420 added review load: every committed byte regenerates; the "
                       "current scorer also prints a review-load column and '(split: all)' in the title")
        return "MATCH-OLD", details
    if old_keys:
        details.append("revision-A markdown predates the source-location line; every original byte and the full "
                       "JSON regenerate, with only that exact new line omitted")
        return "MATCH-OLD", details
    return "MATCH", details


def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="regenerate every table from predictions/ and diff")
    mode.add_argument("--list", action="store_true", help="list the tables, their labels and what is committed")
    mode.add_argument("--export", action="store_true", help="write predictions/ from the local runs/ (author only)")
    ap.add_argument("--label", help="only tables that use this run label (or, with --export, only this label)")
    a = ap.parse_args(argv)
    if a.export:
        runs = ROOT / "runs"
        labels = [a.label] if a.label else sorted(p.name for p in runs.iterdir() if p.is_dir())
        print(f"wrote {export(labels)} prediction files for {len(labels)} labels under predictions/")
        return 0
    todo = [j for j in jobs() if not a.label or a.label in j["labels"]]
    if a.label and not todo:
        print(f"no committed table uses label {a.label}")
        return 1
    if a.list:
        for j in todo:
            have = sum((PREDICTIONS / lb).is_dir() for lb in j["labels"])
            print(f"{j['name']}: {have}/{len(j['labels'])} labels committed ({', '.join(j['labels'])})")
        return 0
    counts = {}
    for j in todo:
        state, details = check_job(j)
        counts[state] = counts.get(state, 0) + 1
        print(f"{state:7s} {j['name']}")
        for x in details:
            print(f"        {x}")
    print("\n" + ", ".join(f"{n} {s}" for s, n in sorted(counts.items())))
    return 1 if counts.get("DIFF") or counts.get("MISSING") else 0


if __name__ == "__main__":
    sys.exit(main())
